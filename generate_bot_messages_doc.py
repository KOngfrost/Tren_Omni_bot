        run_t_val.font.name = "Times New Roman"
        run_t_val.font.size = Pt(14)
        run_t_val._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        p_trig.paragraph_format.space_after = Pt(2)

